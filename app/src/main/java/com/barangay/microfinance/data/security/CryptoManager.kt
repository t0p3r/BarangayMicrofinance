package com.barangay.microfinance.data.security

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import androidx.security.crypto.EncryptedSharedPreferences
import androidx.security.crypto.MasterKey
import java.security.KeyStore
import java.security.SecureRandom
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * CryptoManager: Production implementation of hardware-backed AES-256-GCM encryption.
 * Enforces AES-256 for all locally stored borrower PII (National ID, Phone, TIN).
 * Generates and secures SQLCipher database encryption passphrase.
 */
class CryptoManager(private val context: Context) {

    companion object {
        private const val ANDROID_KEYSTORE_PROVIDER = "AndroidKeyStore"
        private const val MASTER_KEY_ALIAS = "barangay_mf_aes256_master_key"
        private const val AES_GCM_TRANSFORMATION = "AES/GCM/NoPadding"
        private const val GCM_IV_LENGTH_BYTES = 12 // 96-bit IV recommended by NIST
        private const val GCM_TAG_LENGTH_BITS = 128 // 128-bit authentication tag
        private const val CIPHER_PREFIX = "enc:v1:"
        private const val PREFS_FILE = "barangay_secure_vault_prefs"
        private const val DB_PASSPHRASE_KEY = "encrypted_sqlcipher_passphrase"
    }

    private val keyStore: KeyStore = KeyStore.getInstance(ANDROID_KEYSTORE_PROVIDER).apply {
        load(null)
    }

    init {
        ensureMasterKeyExists()
    }

    /**
     * Generates a 256-bit AES Master Key in the Android Hardware Keystore (TEE or StrongBox)
     */
    private fun ensureMasterKeyExists() {
        if (!keyStore.containsAlias(MASTER_KEY_ALIAS)) {
            val keyGenerator = KeyGenerator.getInstance(
                KeyProperties.KEY_ALGORITHM_AES,
                ANDROID_KEYSTORE_PROVIDER
            )

            val spec = KeyGenParameterSpec.Builder(
                MASTER_KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256) // AES-256
                .setRandomizedEncryptionRequired(true)
                .build()

            keyGenerator.init(spec)
            keyGenerator.generateKey()
        }
    }

    private fun getSecretKey(): SecretKey {
        return (keyStore.getEntry(MASTER_KEY_ALIAS, null) as KeyStore.SecretKeyEntry).secretKey
    }

    /**
     * Encrypts plaintext borrower field using AES-256-GCM.
     * Returns structured string: "enc:v1:<base64-iv>:<base64-ciphertext+tag>"
     */
    fun encrypt(plainText: String): String {
        if (plainText.isEmpty()) return ""

        val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, getSecretKey())

        val iv = cipher.iv // 12-byte random IV generated by Android Keystore
        val cipherBytes = cipher.doFinal(plainText.toByteArray(Charsets.UTF_8))

        val ivB64 = Base64.encodeToString(iv, Base64.NO_WRAP)
        val cipherB64 = Base64.encodeToString(cipherBytes, Base64.NO_WRAP)

        return "$CIPHER_PREFIX$ivB64:$cipherB64"
    }

    /**
     * Decrypts AES-256-GCM ciphertext.
     */
    fun decrypt(cipherText: String): String {
        if (!cipherText.startsWith(CIPHER_PREFIX)) {
            return cipherText // Legacy or non-encrypted fallback
        }

        val parts = cipherText.removePrefix(CIPHER_PREFIX).split(":")
        if (parts.size != 2) throw IllegalArgumentException("Corrupted ciphertext structure")

        val iv = Base64.decode(parts[0], Base64.NO_WRAP)
        val cipherBytes = Base64.decode(parts[1], Base64.NO_WRAP)

        val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
        val spec = GCMParameterSpec(GCM_TAG_LENGTH_BITS, iv)
        cipher.init(Cipher.DECRYPT_MODE, getSecretKey(), spec)

        val decryptedBytes = cipher.doFinal(cipherBytes)
        return String(decryptedBytes, Charsets.UTF_8)
    }

    /**
     * Obtains or initializes the 256-bit passphrase for SQLCipher, stored in EncryptedSharedPreferences
     */
    fun getOrCreateDatabasePassphrase(): ByteArray {
        val masterKey = MasterKey.Builder(context)
            .setKeyScheme(MasterKey.KeyScheme.AES256_GCM)
            .build()

        val encryptedPrefs = EncryptedSharedPreferences.create(
            context,
            PREFS_FILE,
            masterKey,
            EncryptedSharedPreferences.PrefKeyEncryptionScheme.AES256_SIV,
            EncryptedSharedPreferences.PrefValueEncryptionScheme.AES256_GCM
        )

        var passphraseB64 = encryptedPrefs.getString(DB_PASSPHRASE_KEY, null)
        if (passphraseB64 == null) {
            val randomBytes = ByteArray(32) // 256 bits
            SecureRandom().nextBytes(randomBytes)
            passphraseB64 = Base64.encodeToString(randomBytes, Base64.NO_WRAP)
            encryptedPrefs.edit().putString(DB_PASSPHRASE_KEY, passphraseB64).apply()
        }

        return Base64.decode(passphraseB64, Base64.NO_WRAP)
    }
}